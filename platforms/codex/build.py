#!/usr/bin/env python3
"""Generate Codex instructions from the shared source, without external deps."""

import argparse
import hashlib
import json
import re
import shutil
from pathlib import Path


PLATFORM = Path(__file__).resolve().parent
ROOT = PLATFORM.parents[1]
SOURCE = ROOT / 'plugins/maister'
DEFAULT_OUTPUT = ROOT / 'plugins/maister-codex'


def frontmatter(text):
    match = re.match(r'^---\n(.*?)\n---\n', text, re.S)
    if not match:
        raise ValueError('Missing Markdown frontmatter')
    fields = {}
    for line in match.group(1).splitlines():
        if ':' in line and not line.startswith(' '):
            key, value = line.split(':', 1)
            fields[key] = value.strip()
    return fields, text[match.end():].lstrip('\n')


def translate(text):
    text = text.replace('CLAUDE_PLUGIN_ROOT', 'MAISTER_PLUGIN_ROOT')
    text = text.replace('CLAUDE_PROJECT_DIR', 'MAISTER_PROJECT_DIR')
    text = text.replace('CLAUDE.md', 'AGENTS.md')
    text = text.replace('claude-md-template.md', 'agents-md-template.md')
    text = text.replace('Claude Code', 'Codex')
    text = text.replace('maister:', 'maister-')
    text = re.sub(r'/maister-([a-z*][a-z0-9*-]*)', r'$maister-codex:maister-\1', text)
    for old, new in (
        ('AskUserQuestion', 'Maister user decision'),
        ('TaskCreate', 'Maister task create'), ('TaskUpdate', 'Maister task update'),
        ('TaskList', 'Maister task list'), ('TaskGet', 'Maister task get'),
        ('EnterPlanMode', 'Maister planning-only mode'),
        ('ExitPlanMode', 'Maister plan approval'),
        ('Skill/Task tools', 'skill loading / agent dispatch adapters'),
        ('Skill tool', 'Load Maister skill'), ('Task tool', 'Dispatch Maister agent'),
        ('`Skill` tool', 'Load Maister skill'), ('`Task` tool', 'Dispatch Maister agent'),
        ('Use Skill:', 'Load Maister skill:'),
        ('Task(', 'DispatchAgent('),
        ('subagent_type="Explore"', 'subagent_type="explorer"'),
    ):
        text = text.replace(old, new)
    text = text.replace(
        '| Reading a SKILL.md then doing the work | Skill files are instructions FOR skills | Use Skill tool to invoke |',
        '| Bypassing loaded skill instructions | Skips workflow semantics | Load and execute the complete skill in the parent context |',
    )
    # The source anti-pattern is Claude-specific: Codex intentionally loads skills
    # by reading their full instructions in the parent context.
    text = re.sub(r'^\| Reading a SKILL\.md then doing the work .*$',
                  '| Bypassing loaded skill instructions | Skips the selected workflow | Load and execute the complete skill |',
                  text, flags=re.M)
    text = text.replace('Skills always use Skill tool; agents always use Task tool.',
                        'Skills load in the parent context; agents run as isolated subagents.')
    return text


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2) + '\n')


def build(output=DEFAULT_OUTPUT):
    output = Path(output).resolve()
    # A dedicated output only. Never delete arbitrary --output directories.
    if output == SOURCE or SOURCE in output.parents or output in SOURCE.parents:
        raise ValueError('Output must not overlap source')
    if output.exists():
        if not (output / '.maister-generated').is_file():
            raise ValueError('Refusing to replace an unmarked output directory')
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / '.maister-generated').write_text('Generated by platforms/codex/build.py\n')
    adapter = (PLATFORM / 'runtime/platform.md').read_text()
    hashes = {}
    for source in sorted(SOURCE.rglob('*')):
        if not source.is_file():
            continue
        relative = source.relative_to(SOURCE)
        hashes[str(relative)] = hashlib.sha256(source.read_bytes()).hexdigest()
        if relative.parts[0] in ('.claude-plugin', 'hooks', 'commands'):
            continue
        if str(relative) in ('.mcp.json', 'README.md'):
            continue
        destination = output / str(relative).replace('CLAUDE.md', 'AGENTS.md').replace(
            'claude-md-template.md', 'agents-md-template.md')
        destination.parent.mkdir(parents=True, exist_ok=True)
        if source.suffix != '.md':
            shutil.copyfile(source, destination)
            continue
        text = translate(source.read_text())
        if source.name == 'SKILL.md':
            fields, body = frontmatter(text)
            name = 'maister-' + source.parent.name
            description = fields['description']
            text = f'---\nname: {name}\ndescription: {description}\n---\n\n{adapter}\n\n---\n\n{body}'
            # Internal machinery is loaded explicitly by its parent, never selected
            # implicitly for arbitrary user requests.
            write_policy = fields.get('user-invocable') == 'false'
            if write_policy:
                policy = destination.parent / 'agents/openai.yaml'
                policy.parent.mkdir(parents=True, exist_ok=True)
                policy.write_text('policy:\n  allow_implicit_invocation: false\n')
        destination.write_text(text)
        if relative.parts[0] == 'agents':
            fields, body = frontmatter(text)
            instructions = adapter + '\n\n' + body
            if source.stem == 'docs-operator':
                instructions += '\n\nPreload and follow skills/docs-manager/SKILL.md before executing operations.\n'
            config = (
                'name = ' + json.dumps('maister-' + source.stem) + '\n'
                'description = ' + json.dumps(fields['description']) + '\n'
                'developer_instructions = ' + json.dumps(instructions, ensure_ascii=False) + '\n'
            )
            destination.with_suffix('.toml').write_text(config)
    for command in sorted((SOURCE / 'commands').glob('*.md')):
        fields, body = frontmatter(translate(command.read_text()))
        destination = output / 'skills' / command.stem / 'SKILL.md'
        destination.parent.mkdir(parents=True)
        destination.write_text(
            f'---\nname: maister-{command.stem}\ndescription: {fields["description"]}\n---\n\n'
            + adapter + '\n\n---\n\n' + body
        )
    source_manifest = json.loads((SOURCE / '.claude-plugin/plugin.json').read_text())
    manifest = dict(source_manifest, name='maister-codex',
                    description='Structured, standards-aware development workflows for Codex')
    manifest.update({'skills': './skills/', 'mcpServers': './.mcp.json',
                     'hooks': './hooks/hooks.json'})
    write_json(output / '.codex-plugin/plugin.json', manifest)
    shutil.copyfile(SOURCE / '.mcp.json', output / '.mcp.json')
    shutil.copytree(PLATFORM / 'hooks', output / 'hooks', ignore=shutil.ignore_patterns('__pycache__'))
    shutil.copytree(PLATFORM / 'runtime', output / 'runtime', ignore=shutil.ignore_patterns('__pycache__'))
    shutil.copyfile(PLATFORM / 'README.md', output / 'README.md')
    write_json(output / 'source-coverage.json', hashes)
    return output


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    print(build(parser.parse_args().output))